using Microsoft.EntityFrameworkCore;
using Npgsql;
using SchoolAdmission.Infrastructure.Persistence;

namespace SchoolAdmission.IntegrationTests;

public sealed class PostgreSqlFactAttribute : FactAttribute
{
    public PostgreSqlFactAttribute()
    {
        if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable(PostgreSqlTestDatabase.ConnectionVariable)))
        {
            Skip = $"Set {PostgreSqlTestDatabase.ConnectionVariable} to run against a disposable PostgreSQL database.";
        }
    }
}

public sealed class PostgreSqlTestDatabase : IAsyncLifetime
{
    public const string ConnectionVariable = "SCHOOL_ADMISSION_TEST_CONNECTION";
    private readonly string? _connectionString = Environment.GetEnvironmentVariable(ConnectionVariable);
    private readonly string _schema = $"admission_test_{Guid.NewGuid():N}";
    private bool _schemaCreated;

    public string ConnectionString => new NpgsqlConnectionStringBuilder(_connectionString) { SearchPath = _schema }.ConnectionString;

    public ApplicationDbContext CreateContext()
    {
        return new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>()
            .UseNpgsql(ConnectionString, options => options.MigrationsHistoryTable("__EFMigrationsHistory", _schema))
            .Options);
    }

    public async Task InitializeAsync()
    {
        if (string.IsNullOrWhiteSpace(_connectionString))
        {
            return;
        }

        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand($"CREATE SCHEMA {_schema}", connection);
        await command.ExecuteNonQueryAsync();
        _schemaCreated = true;
        try
        {
            await using var context = CreateContext();
            await context.Database.MigrateAsync();
        }
        catch (Exception originalException)
        {
            try
            {
                await DisposeAsync();
            }
            catch (Exception cleanupException)
            {
                originalException.Data["CleanupException"] = cleanupException;
            }
            throw;
        }
    }

    public async Task DisposeAsync()
    {
        if (!_schemaCreated)
        {
            return;
        }

        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        // The schema name is generated by this fixture, never supplied by a caller.
        await using var command = new NpgsqlCommand($"DROP SCHEMA {_schema} CASCADE", connection);
        await command.ExecuteNonQueryAsync();
        _schemaCreated = false;
    }
}
